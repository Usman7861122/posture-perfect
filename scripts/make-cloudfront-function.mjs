// Writes infra/cloudfront-redirects.js: a CloudFront Function (viewer request) that sends real 301s.
// Run: node scripts/make-cloudfront-function.mjs
import fs from 'node:fs';
import { redirects, prefixRedirects } from '../redirects.mjs';

const host = 'www.postureperfectwellnesscenter.com';
const code = `// Generated by scripts/make-cloudfront-function.mjs. Attach to the distribution as a Viewer request function.
var MAP = ${JSON.stringify(redirects, null, 2)};
var PREFIX = ${JSON.stringify(prefixRedirects)};
var HOST = '${host}';

function redirect(location) {
  return { statusCode: 301, statusDescription: 'Moved Permanently', headers: { location: { value: location } } };
}

function handler(event) {
  var req = event.request;
  var h = req.headers.host ? req.headers.host.value : HOST;
  // apex -> www in one hop
  if (h === 'postureperfectwellnesscenter.com') return redirect('https://' + HOST + req.uri);
  var uri = req.uri;
  var key = uri.charAt(uri.length - 1) === '/' ? uri : uri + '/';
  if (MAP[key] && key !== MAP[key]) return redirect('https://' + HOST + MAP[key]);
  for (var i = 0; i < PREFIX.length; i++) {
    if (key.indexOf(PREFIX[i][0]) === 0 && !MAP[key]) return redirect('https://' + HOST + PREFIX[i][1]);
  }
  // /about etc. without trailing slash -> add it
  if (uri.indexOf('.') === -1 && uri.charAt(uri.length - 1) !== '/') return redirect('https://' + HOST + uri + '/');
  return req;
}
`;
fs.mkdirSync(new URL('../infra/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../infra/cloudfront-redirects.js', import.meta.url), code);
console.log('written', Object.keys(redirects).length, 'redirects');
